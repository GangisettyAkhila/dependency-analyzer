def test_repeated_scan_sqlite_caching():
    payload = {
        "filename": "package.json",
        "content": '{"name": "cached-demo", "dependencies": {"express": "4.16.0"}}'
    }
    t0 = time.time()
    res1 = client.post("/api/scan/text", json=payload)
    t1 = time.time()
    assert res1.status_code == 200

    res2 = client.post("/api/scan/text", json=payload)
    t2 = time.time()
    assert res2.status_code == 200
    assert (t2 - t1) <= (t1 - t0) + 0.05

def test_past_scans_list_get_and_delete():
    payload = {
        "filename": "requirements.txt",
        "content": "flask==0.12.2"
    }
    scan_res = client.post("/api/scan/text", json=payload)
    assert scan_res.status_code == 200
    scan_id = scan_res.json()["id"]

    list_res = client.get("/api/scans")
    assert list_res.status_code == 200
    scans = list_res.json()
    assert any(s["id"] == scan_id for s in scans)

    get_res = client.get(f"/api/scans/{scan_id}")
    assert get_res.status_code == 200
    assert get_res.json()["id"] == scan_id

    del_res = client.delete(f"/api/scans/{scan_id}")
    assert del_res.status_code == 200

    get_res_after = client.get(f"/api/scans/{scan_id}")
    assert get_res_after.status_code == 404

def test_scan_deletion_cascade_ai_insights():
    from database import get_db_connection
    payload = {
        "filename": "package.json",
        "content": '{"name": "vulnerable-app", "dependencies": {"express": "4.16.0"}}'
    }
    scan_res = client.post("/api/scan/text", json=payload)
    assert scan_res.status_code == 200
    scan_id = scan_res.json()["id"]

    conn = get_db_connection()
    cursor = conn.cursor()
    cursor.execute("SELECT COUNT(*) as cnt FROM findings WHERE scan_id = ?", (scan_id,))
    finding_cnt = cursor.fetchone()["cnt"]
    cursor.execute("SELECT COUNT(*) as cnt FROM ai_insights WHERE finding_id IN (SELECT id FROM findings WHERE scan_id = ?)", (scan_id,))
    ai_cnt = cursor.fetchone()["cnt"]
    conn.close()

    assert finding_cnt > 0
    assert ai_cnt > 0

    del_res = client.delete(f"/api/scans/{scan_id}")
    assert del_res.status_code == 200

    conn = get_db_connection()
    cursor = conn.cursor()
    cursor.execute("SELECT COUNT(*) as cnt FROM scans WHERE id = ?", (scan_id,))
    assert cursor.fetchone()["cnt"] == 0
    cursor.execute("SELECT COUNT(*) as cnt FROM dependencies WHERE scan_id = ?", (scan_id,))
    assert cursor.fetchone()["cnt"] == 0
    cursor.execute("SELECT COUNT(*) as cnt FROM dependency_edges WHERE scan_id = ?", (scan_id,))
    assert cursor.fetchone()["cnt"] == 0
    cursor.execute("SELECT COUNT(*) as cnt FROM findings WHERE scan_id = ?", (scan_id,))
    assert cursor.fetchone()["cnt"] == 0
    cursor.execute("SELECT COUNT(*) as cnt FROM ai_insights WHERE finding_id IN (SELECT id FROM findings WHERE scan_id = ?)", (scan_id,))
    assert cursor.fetchone()["cnt"] == 0
    cursor.execute("SELECT COUNT(*) as cnt FROM reports WHERE scan_id = ?", (scan_id,))
    assert cursor.fetchone()["cnt"] == 0
    conn.close()

