# --- SECTION 14 ENDPOINT TESTS ---

def test_section_14_project_endpoints():
    # 1. Create project
    create_res = client.post("/api/projects", json={
        "name": "E-Commerce App",
        "ecosystem": "npm",
        "repository_url": "https://github.com/myorg/ecommerce"
    })
    assert create_res.status_code == 200
    proj = create_res.json()
    proj_id = proj["id"]
    assert proj["name"] == "E-Commerce App"

    # 2. List projects
    list_res = client.get("/api/projects")
    assert list_res.status_code == 200
    assert any(p["id"] == proj_id for p in list_res.json())

    # 3. Scan project
    scan_res = client.post(f"/api/projects/{proj_id}/scan", data={
        "filename": "package.json",
        "content": '{"name": "ecommerce", "dependencies": {"axios": "0.18.0"}}'
    })
    assert scan_res.status_code == 200
    scan_id = scan_res.json()["id"]

    # 4. Project scan history
    history_res = client.get(f"/api/projects/{proj_id}/scans")
    assert history_res.status_code == 200
    assert any(s["id"] == scan_id for s in history_res.json())

    # 5. Get Scan Dependencies
    deps_res = client.get(f"/api/scans/{scan_id}/dependencies")
    assert deps_res.status_code == 200
    assert "dependencies" in deps_res.json()

    # 6. Get Scan Findings
    findings_res = client.get(f"/api/scans/{scan_id}/findings")
    assert findings_res.status_code == 200
    assert "findings" in findings_res.json()

    # 7. Get Scan Graph
    graph_res = client.get(f"/api/scans/{scan_id}/graph")
    assert graph_res.status_code == 200
    assert "nodes" in graph_res.json()
    assert "edges" in graph_res.json()

    # 8. Get Scan Report
    report_res = client.get(f"/api/scans/{scan_id}/report")
    assert report_res.status_code == 200
